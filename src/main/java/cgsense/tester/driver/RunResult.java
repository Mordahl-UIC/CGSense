package cgsense.tester.driver;

import java.nio.file.Path;
import java.util.List;

public final class RunResult {
  final int index; // which repeat this was (0..N-1)
  final Path runDir; // where the run's output files are (dumps, reports, logs)

  /** Build command line used for this run. */
  final List<String> command;

  /** Process exit code; null when no exit code was available. */
  final Integer exitCode;

  final boolean timedOut;

  final double durationSeconds; // the time it took for the test run to complete, in seconds.
  final List<Path> dumpFiles;

  // the list of dump files generated by the agent during the test run. These files
  // contain the recorded call graph data and are used for analysis.
  final List<Path>
      reportDirs; // the list of directories containing test reports generated by the build tool

  // (e.g., Surefire reports for Maven or Gradle test reports). These directories
  // provide detailed information about the test execution, including passed and
  // failed tests.

  /** Per-test outcomes written by dyncg's Gradle test listener; null for Maven runs. */
  final Path testLog;

  // contains per-test outcomes and is only applicable for Gradle runs; it will be null
  // for Maven runs, as Maven does not produce this log in the same format.

  RunResult(
      int index,
      Path runDir,
      List<String> command,
      Integer exitCode,
      boolean timedOut,
      double durationSeconds,
      List<Path> dumpFiles,
      List<Path> reportDirs,
      Path testLog) {
    this.index = index;
    this.runDir = runDir;
    this.command = command;
    this.exitCode = exitCode;
    this.timedOut = timedOut;
    this.durationSeconds = durationSeconds;
    this.dumpFiles = dumpFiles;
    this.reportDirs = reportDirs;
    this.testLog = testLog;
  }
}
