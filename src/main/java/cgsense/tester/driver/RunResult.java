package cgsense.tester.driver;

import java.nio.file.Path;
import java.util.List;

/*RunResult is a small data container that holds everything one test run produced. It's the "receipt" TestRunner.runTests hands back: what was run, how it ended, and where 
its output files are. It has no logic, only fields and a constructor.*/

/*VersionRunner.run
  └─ for each repeat:
        TestRunner.runTests(...)  ──creates──►  RunResult  (exit, time, dumps, reports, log)
        print it, runs.add(run)
  └─ GraphBuilder.build(..., runs, ...)
        ├─ loadRun(run)               ← run.dumpFiles   → methods + edges
        ├─ SurefireReports.parse(...) ← run.reportDirs / run.testLog → test statuses
        └─ "runs": [...]              ← run.index, exitCode, timedOut, durationSeconds, command, runDir
*/

final class RunResult {
    final int index;        // which repeat this was (0..N-1)
    final Path runDir;      // where the run's output files are (dumps, reports, logs)
 /** Build command line used for this run. */
    final List<String> command;     // the command line that was executed to run the tests, including the build tool, test goals, and any relevant options. This is useful for debugging and reproducing the run if needed.
   /** Process exit code; null when no exit code was available. */
    final Integer exitCode;     // the exit code returned by the test process. A null value indicates that the process did not produce an exit code, which can happen if the process was terminated or failed to start.
    final boolean timedOut;     // true if the test run exceeded the specified timeout and was terminated. This helps identify runs that did not complete successfully due to time constraints.
    final double durationSeconds;   // the time it took for the test run to complete, in seconds.
    final List<Path> dumpFiles;     // the list of dump files generated by the agent during the test run. These files contain the recorded call graph data and are used for analysis.
    final List<Path> reportDirs;       // the list of directories containing test reports generated by the build tool (e.g., Surefire reports for Maven or Gradle test reports). These directories provide detailed information about the test execution, including passed and failed tests.
    /** Per-test outcomes written by dyncg's Gradle test listener; null for Maven runs. */
    final Path testLog;         // the path to the test log file generated by dyncg's Gradle test listener. This file contains per-test outcomes and is only applicable for Gradle runs; it will be null for Maven runs, as Maven does not produce this log in the same format.

    RunResult(int index, Path runDir, List<String> command, Integer exitCode, boolean timedOut,
            double durationSeconds, List<Path> dumpFiles, List<Path> reportDirs, Path testLog) {
        this.index = index;
        this.runDir = runDir;
        this.command = command;
        this.exitCode = exitCode;
        this.timedOut = timedOut;
        this.durationSeconds = durationSeconds;
        this.dumpFiles = dumpFiles;
        this.reportDirs = reportDirs;
        this.testLog = testLog;
    }
}
